def spectral_sky_from_epw(location_description: str = "") -> str:
    """Guide: reconstruct a physical spectral sky from an EPW hour and read its circadian metrics."""
    return (
        f"Reconstruct the physical spectral sky from an EPW for: {location_description}\n"
        "You need an EPW path and a target moment (month, day, hour); the location comes from the EPW\n"
        "LOCATION header. Honor the run/emit contract throughout.\n"
        "1) atmosphere_from_epw(epw, month, day, hour) -> inspect the EPW-derived atmospheric state\n"
        "   (AOD500, PWV, ozone, pressure, albedo) and its provenance so the inputs are auditable.\n"
        "2) spectral_sky_from_epw(epw, month, day, hour, engine='spectrl2') -> the canonical record:\n"
        "   1nm direct-normal + sky-diffuse spectra (380-780nm), solar geometry, and clearness Kt.\n"
        "   Pass surface_tilt_deg for a tilted/vertical receiver's spectral ground glow. engine='smarts'\n"
        "   is opt-in and needs $SMARTSPATH; spectrl2 (default) is pure Python.\n"
        "3) Feed the sky-diffuse (or direct-normal) spectrum as `spd=` to alpha_opic and spectral_metrics\n"
        "   for the CIE S 026 alpha-opic suite, CCT/Duv, and mel-DER. NOTE the returned EDIs are\n"
        "   shape/relative indicators unless the spectrum carries absolute W/m2/nm magnitude.\n"
        "4) For a whole year / hour-subset of artifacts (SPD set, band matrix, spectral .wea, sidecar),\n"
        "   use spectral_epw (long-running). For a native Radiance 20-band matrix use spectral_sky_native\n"
        "   (gensdaymtx; trim the EPW or pass `timeout` — a full year is many minutes of CPU).\n"
        "5) To RENDER this sky (hand it to run_grid/run_image), bridge it: spd_to_channels on the\n"
        "   sky-diffuse and again on the direct-normal spectrum, then colored_sky(diffuse_channels,\n"
        "   direct_channels, ...). Pass the record's geometry VERBATIM alongside them:\n"
        "     sun_zenith_deg  = rec['geometry']['zenith_deg']\n"
        "     sun_azimuth_deg = rec['geometry']['azimuth_deg']\n"
        "   This is REQUIRED for a physically consistent scene, not an optimisation. This tool's `hour`\n"
        "   is an EPW hour-ENDING label and its geometry is evaluated at the mid-interval instant\n"
        "   (hour-0.5, since the row's DNI/DHI are averaged over the preceding hour); colored_sky's\n"
        "   `hour` is a wall-clock instant that gendaylit re-derives the sun from. Passing the same\n"
        "   integer to both leaves the spectrum and the traced sky half an hour — 7.5 deg of diurnal\n"
        "   arc — apart, and nothing raises.\n"
        "Report: solar zenith, Kt, the atmosphere inputs, and CCT / mel-DER / mel-EDI of the sky."
    )

def hcl_studio(space_description: str = "", daylight_aware: bool = True) -> str:
    """Guide: the full start-to-finish HCL artificial-lighting journey — goal → fixture design →
    simulate → visualize/analyze — with a resumable study brief. The front door to a complete study."""
    daylight_phase = (
        "3) DAYLIGHT BASELINE (daylight_aware): run_grid (daylight) or run_annual at the goal's stated\n"
        "   occupied condition; record e_daylight_lux and mel_edi_daylight in daylight_baseline. This\n"
        "   credits the CIRCADIAN budget only — it does NOT reduce the installed visual flux (no-daylight\n"
        "   case must still meet Em).\n"
        if daylight_aware else
        "3) DAYLIGHT BASELINE: skipped (daylight_aware=False) — electric-only study.\n")
    return (
        f"Conduct a complete human-centric ARTIFICIAL-lighting study for: {space_description}\n"
        "Maintain ONE study brief across phases. After EVERY phase call save_brief(study, {changed keys});\n"
        "at the start call load_brief(study) and, if it is populated, summarize where the study left off\n"
        "and resume. Honor the run/emit contract throughout (emit-only is fine; the report still renders).\n\n"
        "0) ORIENT: validate(); radiance_status(); daysim_status(). Tell the user what will RUN vs EMIT.\n"
        "   Pick a study slug and the channel_type (3 vs 9) ONCE — keep it consistent every later phase.\n"
        "1) GOAL: pick the circadian standard (WELL v2 L03 / Brown 2022 / ISO-CIE 8995-1 / EN 17037) →\n"
        "   mel-EDI target at the VERTICAL eye plane, and the occupied CONDITION it applies at (e.g. clear\n"
        "   noon). Pick the visual task → EN 12464-1 Em/UGR/Uo/Ra (resource hcl://compliance/en_12464_1).\n"
        "2) SPACE: dimensions, mounting/ceiling height, work-plane + eye height, surface reflectances,\n"
        "   maintenance factor; orientation + glazing if the daylight branch is on. If a real CAD model\n"
        "   exists, import_geometry ingests a Wavefront .obj (+ per-group material_map) into the\n"
        "   per-channel geometry_set/material_sets that phase 6's run_grid/run_annual consume (run-or-emit;\n"
        "   obj2rad/xform) -- otherwise the geometry is hand-authored. When imported, derive_sensors=True\n"
        "   ALSO yields the phase-6 sensors for free (result['grid_points'] = work-plane, "
        "   result['observer_points'] = eye-level), and -- if the daylight branch is on -- set\n"
        "   north_angle_deg so the room aligns to the sun's fixed +Y=true-north frame (else daylight is\n"
        "   azimuth-wrong).\n"
        f"{daylight_phase}"
        "4) FIXTURE SIZING: recommend_fixtures with the space + targets (+ mel_edi_daylight from phase 3).\n"
        "   Read back required_flux_lm, fixture_count, layout, target_cct_band, binding_constraint, and\n"
        "   the assumptions/caveats. If supplementary_fixtures_advised, raise vertical/indirect light.\n"
        "   NOTE: this sizing is FIRST-PRINCIPLES / ILLUSTRATIVE (lumen-method UF + an illustrative LED\n"
        "   mel-DER palette, not measured product data) and MUST be confirmed against the real photometry\n"
        "   (the phase-5 IES) before you trust the numbers.\n"
        "5) INSTANTIATE: have the user supply a real IES that MATCHES the spec. ies_analyze it (check\n"
        "   lumens/efficacy/distribution vs the spec and recompute UF from the real photometry), then\n"
        "   ies_to_radiance to place it on the recommended layout positions.\n"
        "6) SIMULATE: run_grid (daylight + electric + combined) with BOTH horizontal work-plane sensors\n"
        "   AND vertical eye-height sensors (mel-EDI@eye is vertical) -- if you imported the room in phase 2,\n"
        "   these are exactly result['grid_points'] and result['observer_points'] (pass them as `points`).\n"
        "   Optionally run_annual + nvrd for dose/alertness — prefer the annual/occupied-hours result for\n"
        "   the circadian verdict. For the VISUAL daylighting verdict (DA/UDI/sDA/ASE + Daylight Factor)\n"
        "   run annual_daylight + daylight_factor on the same points (see the annual_daylight_study prompt).\n"
        "7) CONTROLS & ENERGY: daylight_savings → daylight-responsive power reduction and kWh/m²·yr.\n"
        "8) REPORT: assemble the brief and call build_report(study, brief). Narrate the headline verdict\n"
        "   inline: target vs achieved (Em, mel-EDI, UGR, Uo, Ra), pass/fail, energy, and what to change.\n"
        "Interpret circadian metrics against the chosen standard; flag the mel-EDI↔UGR conflict if any."
    )


