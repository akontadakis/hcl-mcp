        "   An unmapped group HARD-FAILS; a mixed usemtl/bare-g OBJ HARD-FAILS rather than dropping faces.\n"
        "   units=mm|cm|m|ft, up_axis=Y|Z (a bbox warning flags a wrong unit/axis). Read back groups +\n"
        "   warnings.\n"
        "   ** NORTH (silent-wrong if skipped): set north_angle_deg = the true clockwise azimuth (0=N,90=E)\n"
