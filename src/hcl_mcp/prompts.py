"""MCP prompt builders for the hcl_mcp server.

Every public function here is a pure guide-text builder (no server-only state). They are
registered as MCP prompts by `hcl_mcp.server` via its `mcp.prompt(...)` loop and
re-exported from `hcl_mcp.server` for backward compatibility.

Deliberately no count in this sentence: it read "These 12 functions" through two additions
(13 at the time of writing) because nothing fails when a prose number goes stale. The
registration tuple in `server.py` is the only count that is load-bearing -- it decides what
a client can actually call, and a function defined here but absent from that tuple is dark.
"""


def electric_lighting_design(space_description: str = "") -> str:
    """Guide: a full electric + daylight HCL design pass with savings and EN 12464-1 interpretation."""
    return (
        f"Run an electric-lighting + daylight HCL design pass for: {space_description}\n"
        "1) ies_analyze the luminaire(s) (lumens, watts, efficacy, beam/field, zonal flux).\n"
        "2) ies_to_radiance to place them (placement grid or explicit positions). OR -- if the CAD export\n"
        "   carries type:'luminaire' markers -- import_geometry(material_map={...,'lum':{type:'luminaire',\n"
        "   ies:...}}) returns result['electric_lights'], a DROP-IN payload (fixtures already positioned in\n"
        "   the room's world frame) you pass straight to run_grid/run_image -- they run ies2rad + colorize.\n"
        "3) run_grid with the geometry + materials + sky AND the electric_lights input -> daylight,\n"
        "   electric, and combined photopic illuminance + UGR + mel-EDI at the reference points.\n"
        "   (The room's geometry + materials can be hand-authored or produced by import_geometry from a\n"
        "   Wavefront .obj/CAD export -> per-channel scene_sets; if you import + use a sky, set its\n"
        "   north_angle_deg so the room aligns to the sun's fixed +Y=true-north frame.)\n"
        "4) daylight_savings to compute the daylight-responsive power reduction and annual kWh/m².\n"
        "5) Interpret the task-area illuminance, UGR, Uo, and Ra against EN 12464-1 (compliance with\n"
        "   standard='en_12464_1', the appropriate task), plus the mel-EDI vs the circadian target.\n"
        "Report: required vs achieved Ēm/UGR/Uo/Ra (pass/fail), energy saved, and mel-EDI dose."
    )

def spd_to_circadian(spd_description: str = "") -> str:
    """Guide: turn an SPD into circadian metrics + compliance."""
    return (f"Analyze this light source for circadian impact: {spd_description}\n"
            "1) Call spd_to_channels to bin the SPD. 2) Call alpha_opic (use `spd=` for the exact path) "
            "for melanopic EDI. 3) Call spectral_metrics for CCT/Duv and mel-DER. "
            "4) Call compliance with the melanopic EDI against the user's target standard. "
            "Summarize CCT, mel-DER, mel-EDI, and pass/fail.")

