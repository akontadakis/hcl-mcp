"""Pure builders for Daysim command lines + the .hea header text. No execution.

write_hea ports the `.hea` Lark 2.0 writes in `Lark Generate Sub-Hourly wea File.py:104-140`,
keeping Lark's keyword names (`time_step`, `wea_data_file`, `wea_data_short_file`,
`wea_data_short_file_units`) — the names the master-branch ds_shortterm parses
(`src/daysim/read_in_header.c`). It is NOT byte-identical to Lark's header; the divergences
were each checked against the ds_shortterm source and are safe:
  - drops Lark's `project_directory` / `bin_directory` lines — ds_shortterm's shortterm path
    never reads bin_directory and only uses project_directory to rebase OUTPUT paths (a no-op
    when absent; the runner already runs in work_dir);
  - takes the site values as explicit args instead of injecting the `.wea`'s first six lines;
  - adds the recognized `wea_data_file_units` keyword (see below) and a `solar_time` line
    (an unrecognized keyword that read_in_header silently skips — harmless, documents intent).
The hard-required ds_shortterm fields (`wea_data_file`, `time_step`, `latitude`, `longitude`,
`time_zone`) are all present.
"""

DS_SHORTTERM_TIMESTEPS = frozenset({1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30})

def build_epw2wea(epw, wea_out):
    """epw2wea <epw> <wea> -> hourly .wea (units 1 = direct-normal + diffuse-horizontal)."""
    return ["epw2wea", epw, wea_out]

def build_ds_shortterm(hea_path):
    """ds_shortterm <header.hea> -> reads the header, writes the sub-hourly .wea."""
    return ["ds_shortterm", hea_path]

def write_hea(*, input_wea, output_wea, timestep_min, latitude, longitude,
              time_zone, site_elevation, solar_time=0, units=1, input_units=1):
    """Return the Daysim .hea header text ds_shortterm requires (port of the Lark component).

    input_wea: hourly .wea path (from epw2wea). output_wea: sub-hourly .wea path ds_shortterm writes.
    timestep_min: minutes within the hour (6 = default sub-hourly). The ds_shortterm genshortterm guard
    accepts only minutes in {1,2,3,4,5,6,10,12,15,20,30} (default 6); values outside this set (e.g. 60)
    are rejected at runtime by ds_shortterm even though they are textually valid in the .hea.
    input_units: units of the INPUT hourly .wea (1 = direct-normal + diffuse-horizontal, as epw2wea
    writes). We emit the keyword spelling read_in_header.c actually matches (`wea_data_file_units`);
    epw2wea's own `.wea` writes the UNRECOGNIZED `weather_data_file_units`, which the header parser
    silently ignores — so we set it explicitly rather than relying on ds_shortterm's internal default.
    units: units of the OUTPUT short .wea (1 keeps the solar radiation, 2 converts to photopic).
    longitude and time_zone use the DAYSIM convention — WEST-positive longitude, time_zone in DEGREES
    (= -15 × UTC offset). These match what epw2wea writes; do NOT pass raw EPW East-positive coords.
    latitude/longitude/time_zone/site_elevation/solar_time: site information.
    """
    if timestep_min not in DS_SHORTTERM_TIMESTEPS:
        raise ValueError(
            f"timestep_min={timestep_min!r} is rejected by ds_shortterm at runtime; "
            f"choose one of {sorted(DS_SHORTTERM_TIMESTEPS)} (minutes that evenly divide the hour).")
    site = (
        "##################\n"
        "# site information\n"
        "##################\n"
        f"latitude {latitude}\n"
        f"longitude {longitude}\n"
        f"time_zone {time_zone}\n"
        f"site_elevation {site_elevation}\n"
        f"solar_time {solar_time}\n"
    )
    return (
        "#====================\n"
        "# DAYSIM header file (generated by hcl_daysim; port of Lark 2.0 Generate Sub-Hourly wea)\n"
        "#====================\n"
        "\n"
        f"{site}"
        "\n"
        "# input data name\n"
        f"wea_data_file {input_wea}\n"
        "# units of the input .wea: 1 = direct-normal + diffuse-horizontal irradiance.\n"
        "# (recognized spelling; epw2wea writes a 'weather_'-prefixed variant ds_shortterm ignores)\n"
        f"wea_data_file_units {input_units}\n"
        "\n"
        "first_weekday 1\n"
        "# every n minutes\n"
        f"time_step {timestep_min}\n"
        "# output data name\n"
        f"wea_data_short_file {output_wea}\n"
        "# 1 keeps the solar radiation, 2 converts it to photopic\n"
        f"wea_data_short_file_units {units}\n"
    )
